"""Export ARK graph → Python standalone (.py) ou ONNX.

PyTorch .py : génère un module nn.Module reconstructible sans ARK,
avec les params codés en dur. Permet d'utiliser le modèle hors de l'app.

ONNX : compile + torch.onnx.export. Demande un input shape réel.
"""
from __future__ import annotations
from pathlib import Path
import json
import torch

from ark.core.graph_compiler import compile_scene


# ============================================================
# Python standalone
# ============================================================

_PY_HEADER = '''"""Auto-generated by ARK — standalone PyTorch model.

Reconstruit l'architecture du graph ARK en code Python pur. Pas de
dépendance à ARK ou à la registry — juste torch.

Usage:
    from this_module import build_model
    model = build_model()
    out = model(torch.randn({input_shape}))
"""
from __future__ import annotations
import torch
import torch.nn as nn


# Architecture metadata
ARK_NAME = {name!r}
ARK_VERSION = "ark-export-v1"
INPUT_SHAPE = {input_shape}
OUTPUT_SHAPE = {output_shape}


def _act(name):
    return {{
        "relu": nn.ReLU, "gelu": nn.GELU, "tanh": nn.Tanh,
        "sigmoid": nn.Sigmoid, "softmax": lambda: nn.Softmax(dim=-1),
        "none": nn.Identity,
    }}.get((name or "none").lower(), nn.Identity)()


'''


def export_python(scene, path: str | Path, num_classes: int | None = None,
                   name: str = "ark_model") -> Path:
    """Génère un script .py reconstructible.

    Stratégie : on compile la scene → obtient ordered nodes + modules.
    Puis on émet code qui reconstruit les modules un à un via leur type+params,
    et assemble dans GraphModule simplifié avec forward topologique.
    """
    cg = compile_scene(scene, num_classes=num_classes)
    model = cg.model
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)

    nodes = [(n, getattr(n, 'spec', None)) for n in scene.nodes()]
    # Map id → spec.name + params
    by_id = {}
    for n in scene.nodes():
        by_id[n.id] = (n.spec.name, dict(n.params))

    # Incoming edges
    incoming = {}
    for c in scene.connections():
        if c.start_socket and c.end_socket:
            src_id = c.start_socket.parent_node.id
            dst_id = c.end_socket.parent_node.id
            incoming.setdefault(dst_id, []).append(src_id)

    ordered_ids = [n.id for n in model.ordered_nodes]

    lines = [_PY_HEADER.format(name=name,
                                input_shape=tuple(cg.input_shape),
                                output_shape=tuple(cg.output_shape))]
    lines.append("class ArkModel(nn.Module):")
    lines.append("    def __init__(self):")
    lines.append("        super().__init__()")
    # Émet le code de construction des modules nommés
    module_names: dict[str, str] = {}
    for nid in ordered_ids:
        if nid not in by_id:
            continue
        ntype, params = by_id[nid]
        var = _safe_name(nid)
        code = _emit_module_code(var, ntype, params)
        if code:
            lines.append(f"        {code}")
            module_names[nid] = var
    # Auto-head si présent
    if cg.num_classes is not None and not any("Linear(" in l and f"{cg.num_classes}" in l for l in lines):
        # Génère un auto_head si pas déjà couvert
        pass

    # Forward
    lines.append("")
    lines.append("    def forward(self, x):")
    lines.append("        cache = {}")
    input_id = model.input_id
    lines.append(f"        cache[{input_id!r}] = x")
    for nid in ordered_ids:
        if nid == input_id or nid not in module_names:
            continue
        ups = incoming.get(nid, [])
        if not ups:
            continue
        ups_str = ", ".join(f"cache[{u!r}]" for u in ups)
        var = module_names[nid]
        if by_id.get(nid, (None, None))[0] in ("residual_add",):
            lines.append(f"        cache[{nid!r}] = {ups_str}")
            lines.append(f"        # residual_add : sum")
            lines.append(f"        cache[{nid!r}] = sum([{ups_str}])")
        else:
            lines.append(f"        cache[{nid!r}] = self.{var}({ups_str})")
    lines.append(f"        return cache[{model.output_id!r}]")
    lines.append("")
    lines.append("")
    lines.append("def build_model():")
    lines.append("    return ArkModel()")
    lines.append("")
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append("    m = build_model()")
    lines.append(f"    x = torch.randn(1, *INPUT_SHAPE)")
    lines.append("    y = m(x)")
    lines.append('    print(f"input {x.shape} → output {y.shape}")')
    lines.append(f'    print(f"params {{sum(p.numel() for p in m.parameters()):,}}")')

    out.write_text("\n".join(lines))
    return out


def _safe_name(nid: str) -> str:
    return "n_" + "".join(c if (c.isalnum() or c == "_") else "_" for c in nid)


def _emit_module_code(var: str, ntype: str, params: dict) -> str | None:
    """Retourne `self.<var> = nn.Module(...)` pour le type donné. None si skip."""
    if ntype == "dense":
        n = int(params.get("neurons", 128))
        act = params.get("activation", "relu")
        dr = float(params.get("dropout", 0))
        # In-features inconnu à priori — utilise LazyLinear pour résoudre au 1er forward
        layers = [f"nn.Flatten()", f"nn.LazyLinear({n})", f"_act({act!r})"]
        if dr > 0:
            layers.append(f"nn.Dropout({dr})")
        return f"self.{var} = nn.Sequential({', '.join(layers)})"
    if ntype == "conv2d":
        f = int(params.get("filters", 32))
        k = int(params.get("kernel_size", 3))
        act = params.get("activation", "relu")
        return (f"self.{var} = nn.Sequential("
                f"nn.LazyConv2d({f}, kernel_size={k}, padding={k // 2}), "
                f"_act({act!r}))")
    if ntype == "normalize":
        kind = params.get("kind", "batchnorm")
        if kind == "batchnorm":
            return f"self.{var} = nn.LazyBatchNorm2d()"
        if kind == "layernorm":
            return f"self.{var} = nn.LayerNorm(0)  # dim runtime-resolved"
    if ntype == "attention":
        nh = int(params.get("n_heads", 4))
        return f"self.{var} = _AttnHelper({nh})"
    if ntype == "transformer_block":
        nh = int(params.get("n_heads", 4))
        ff = int(params.get("d_ff", 256))
        return f"self.{var} = _TransformerHelper({nh}, {ff})"
    if ntype == "residual_add":
        return None  # handled inline in forward
    if ntype in ("image_input", "tabular_input", "text_input",
                  "adam", "cross_entropy", "constant",
                  "observer", "trigger_rule",
                  "plot_scatter", "plot_line", "load_image", "save_image",
                  "diffusion_model_loader", "clip_text_encode",
                  "empty_latent_image", "k_sampler", "vae_encode", "vae_decode",
                  "lora_loader", "controlnet_apply",
                  "hf_model_loader", "hf_tokenizer", "hf_pipeline",
                  "webcam", "microphone"):
        return None
    return f"# TODO: {ntype} — not yet exportable"


# ============================================================
# ONNX
# ============================================================

def export_onnx(scene, path: str | Path, num_classes: int | None = None,
                  opset: int = 17, dynamic_batch: bool = True) -> Path:
    """Compile + export ONNX via torch.onnx.export."""
    cg = compile_scene(scene, num_classes=num_classes)
    model = cg.model
    model.eval()
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    sample = torch.randn(1, *cg.input_shape)
    dyn = {"input": {0: "batch"}, "output": {0: "batch"}} if dynamic_batch else None
    torch.onnx.export(
        model, sample, str(out),
        input_names=["input"], output_names=["output"],
        opset_version=opset, dynamic_axes=dyn,
    )
    return out
